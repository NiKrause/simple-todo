/**
 * Render the chapter's parts list into the README from the same source the
 * intro dialog reads.
 *
 * The list exists in one place — `chapter-parts.js` for the structure,
 * `i18n/en.json` for the prose — and appears in two: the dialog somebody opens
 * on first launch, and the README somebody reads on GitHub. Written twice they
 * drift, and the version numbers drift first, because a `pnpm up` moves them
 * and touches no prose at all.
 *
 * So the README block is generated. Versions come from `package.json`, and for
 * a package that arrives with another one, from the lockfile — a reader who
 * finds `iso-webauthn-varsig` in there is owed the version they actually have,
 * not the version somebody typed once.
 *
 *   node scripts/sync-chapter-readme.mjs           write the block
 *   node scripts/sync-chapter-readme.mjs --check   fail if it is stale
 *
 * `--check` is what the unit test runs, so a change to the dialog's wording
 * that forgets the README fails before review rather than after it.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { CHAPTER_PARTS } from '../src/lib/chapter-parts.js';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const START_MARKER = '<!-- chapter-parts:start -->';
export const END_MARKER = '<!-- chapter-parts:end -->';

/**
 * Where a package's version can be read from.
 *
 * Direct dependencies are in `package.json`; anything else is in the lockfile
 * under a key of the form `'name@version':`. Scoped names contain an `@` of
 * their own, hence the anchored match on the name rather than a split.
 *
 * @param {string} name
 * @param {Record<string, string>} declared
 * @param {string} lockfile
 * @returns {string | null}
 */
export function resolveVersion(name, declared, lockfile) {
	// Verbatim, caret and all: `^4.0.0` is what this project actually pins, and
	// printing `4.0.0` would claim a precision the manifest does not have. The
	// lockfile path below returns an exact version because that is what it holds.
	const direct = declared[name];
	if (direct) return direct;

	const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
	const match = lockfile.match(new RegExp(`^\\s*'${escaped}@([^'@]+)':`, 'm'));
	return match ? match[1] : null;
}

/**
 * @param {{ parts: typeof CHAPTER_PARTS, strings: any, declared: Record<string, string>, lockfile: string }} input
 * @returns {string}
 */
export function renderBlock({ parts, strings, declared, lockfile }) {
	const lines = [
		START_MARKER,
		'',
		'<!-- Generated by scripts/sync-chapter-readme.mjs from src/lib/chapter-parts.js',
		'     and src/lib/i18n/en.json — the same source the intro dialog reads.',
		'     Edit those, then run the script. Edits here are overwritten. -->',
		'',
		`### ${strings.heading}`,
		'',
		strings.goal,
		'',
		`### ${strings.partsHeading}`,
		''
	];

	for (const part of parts) {
		const copy = strings.parts[part.key];
		if (!copy) throw new Error(`No translation for chapter part "${part.key}".`);

		const named = part.packages.map((name) => {
			const version = resolveVersion(name, declared, lockfile);
			if (!version) throw new Error(`Could not resolve a version for "${name}".`);
			return `\`${name}@${version}\``;
		});
		if (part.protocol) named.push(`\`${part.protocol}\``);

		// The "not switched on" case is worth marking in the README, where there
		// is room for it, rather than leaving a reader to infer it from prose.
		const suffix = part.unused ? ' _(not used)_' : '';
		lines.push(`- **${copy.label}** — ${named.join(', ')}${suffix}  `);
		lines.push(`  ${copy.text}`);
	}

	lines.push('', END_MARKER);
	return lines.join('\n');
}

/**
 * @param {string} readme
 * @param {string} block
 * @returns {string}
 */
export function replaceBlock(readme, block) {
	const start = readme.indexOf(START_MARKER);
	const end = readme.indexOf(END_MARKER);
	if (start === -1 || end === -1) {
		throw new Error(`README.md has no ${START_MARKER} / ${END_MARKER} pair to write into.`);
	}
	if (end < start) {
		throw new Error(`${END_MARKER} appears before ${START_MARKER} in README.md.`);
	}
	return readme.slice(0, start) + block + readme.slice(end + END_MARKER.length);
}

/** @returns {Promise<{ current: string, expected: string }>} */
export async function buildReadme() {
	const [readme, packageJson, lockfile, translations] = await Promise.all([
		readFile(path.join(rootDir, 'README.md'), 'utf8'),
		readFile(path.join(rootDir, 'package.json'), 'utf8'),
		readFile(path.join(rootDir, 'pnpm-lock.yaml'), 'utf8'),
		readFile(path.join(rootDir, 'src/lib/i18n/en.json'), 'utf8')
	]);

	const parsed = JSON.parse(packageJson);
	const declared = { ...parsed.devDependencies, ...parsed.dependencies };
	const strings = JSON.parse(translations).intro.chapter;

	const block = renderBlock({ parts: CHAPTER_PARTS, strings, declared, lockfile });
	return { current: readme, expected: replaceBlock(readme, block) };
}

// Only when run, not when imported by the test.
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
	const { current, expected } = await buildReadme();
	const check = process.argv.includes('--check');

	if (current === expected) {
		console.log('README chapter block is up to date.');
	} else if (check) {
		console.error(
			'README chapter block is stale. Run `node scripts/sync-chapter-readme.mjs` and commit the result.'
		);
		process.exit(1);
	} else {
		await writeFile(path.join(rootDir, 'README.md'), expected);
		console.log('README chapter block written.');
	}
}
